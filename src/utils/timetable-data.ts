// Helper to determine the period of a lesson if startPeriod is not set
export function inferPeriodFromTime(timeStr: string, isTutoring = false): { startPeriod: number; endPeriod: number } {
  const [h, m] = (timeStr || '09:00').split(':').map(Number);
  const minutes = (h || 0) * 60 + (m || 0);

  if (isTutoring) {
    if (minutes < 18 * 60) return { startPeriod: 1, endPeriod: 1 };
    if (minutes < 19 * 60) return { startPeriod: 2, endPeriod: 2 };
    if (minutes < 20 * 60) return { startPeriod: 3, endPeriod: 3 };
    if (minutes < 21 * 60) return { startPeriod: 4, endPeriod: 4 };
    return { startPeriod: 5, endPeriod: 5 };
  }

  // School
  if (minutes < 8 * 60 + 50) return { startPeriod: 0, endPeriod: 0 };
  if (minutes < 9 * 60 + 45) return { startPeriod: 1, endPeriod: 1 };
  if (minutes < 10 * 60 + 45) return { startPeriod: 2, endPeriod: 2 };
  if (minutes < 11 * 60 + 45) return { startPeriod: 3, endPeriod: 3 };
  if (minutes < 12 * 60 + 45) return { startPeriod: 4, endPeriod: 4 };
  if (minutes < 14 * 60 + 15) return { startPeriod: 5, endPeriod: 5 };
  if (minutes < 15 * 60 + 10) return { startPeriod: 6, endPeriod: 6 };
  if (minutes < 16 * 60 + 10) return { startPeriod: 7, endPeriod: 7 };
  return { startPeriod: 8, endPeriod: 8 };
}
